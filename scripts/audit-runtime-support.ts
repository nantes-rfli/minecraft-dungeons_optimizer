import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'
import type { EnchantmentRuntimeSupport } from '../src/core/runtimeSupport'

const root = fileURLToPath(new URL('..', import.meta.url))
const server = await createServer({ root, configFile: false, server: { middlewareMode: true, hmr: false, watch: null, ws: false } })
try {
  const { collectRuntimeSupportErrors } = await server.ssrLoadModule('/src/research/runtimeSupportAudit.ts')
  const support = await server.ssrLoadModule('/src/core/runtimeSupport.ts')
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'research/melee-runtime-support.json'), 'utf8'))
  const errors: string[] = collectRuntimeSupportErrors(manifest)
  for (const entry of manifest.entries) for (const ref of entry.assumptionRefs) {
    if (!fs.existsSync(path.join(root, ref.split('#')[0]))) errors.push(`${entry.id}: missing assumption reference ${ref}`)
  }
  if (errors.length) throw new Error(errors.join('\n'))
  const { auditRepresentativeCombinations } = await server.ssrLoadModule('/src/research/runtimeCombinations.ts')
  const usability = auditRepresentativeCombinations()
  const summary = support.runtimeSupportSummaryText()
  const generated = `<!-- runtime-support:start -->\n${summary}\n<!-- runtime-support:end -->`
  for (const file of ['README.md', 'ROADMAP.md']) {
    const location = path.join(root, file)
    const source = fs.readFileSync(location, 'utf8')
    if (!source.includes('<!-- runtime-support:start -->')) throw new Error(`${file}: missing generated summary marker`)
    fs.writeFileSync(location, source.replace(/<!-- runtime-support:start -->[\s\S]*?<!-- runtime-support:end -->/, generated))
  }
  const rows = manifest.entries.map((entry: EnchantmentRuntimeSupport) => {
    const range = entry.runtimePowerRange
    const copies = entry.runtimeMaxCopies === null ? '—' : `${entry.runtimeMaxCopies} / game ${entry.gameMaxCopies}`
    const partners: string[] = support.runtimeCombinationPartners(entry.id)
    return `| ${entry.name} | ${entry.supportLevel} | ${range ? `${range.min}–${range.max}` : entry.supportLevel === 'research-only' ? '—' : 'Broad'} | ${copies} | ${partners.length ? partners.map((id) => support.getEnchantmentRuntimeSupport(id).name).join(', ') : '—'} | ${support.runtimeLimitationLines(entry).join('; ') || '—'} | ${entry.phaseOrigin} | [assumptions](../${entry.assumptionRefs[0]}) |`
  }).join('\n')
  fs.writeFileSync(path.join(root, 'docs/melee-runtime-support.md'), `# Melee runtime support\n\nGenerated by \`npm run audit:runtime-support\` from [manifest](../research/melee-runtime-support.json). Do not edit the generated table.\n\n${summary}\n\nFullは現在のOptimizer scope内の通常対応で、実ゲームの完全再現ではありません。Limitedは具体的なPower・コピー・併用境界。Research-onlyは未登録です。Phase partialは履歴上のcompletion gate、Evidence confidenceは根拠品質で、どちらもsupport levelとは別軸です。\n\n併用制限は制約を持つLimited側の所有edgeとしてmanifestに記録し、表では逆方向も表示します。Sharpness等をPain/Dynamoの制約だけでLimitedにしません。Soul gear合法性はゲーム本来の適用条件であり、Soul Scytheのみという現catalogの範囲は追加制限に数えません。\n\n| Enchant | Runtime | Power | Copies | Unsupported partners (both directions) | Main limitation | Origin | Scenario/model assumptions |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n${rows}\n\n## Practical usability\n\nCurated matrix: total ${usability.total}; supported ${usability.supported}; unsupported ${usability.unsupported} (${JSON.stringify(usability.reasons)}). Unsupported率 ${(100 * usability.unsupported / usability.total).toFixed(1)}%。意図的な拒否例を含むソフトウェア指標で、ゲームcoverageや実利用での発生率ではありません。9 family × 2構成 × 通常/金色I/II/IIIが成功。境界例は別枠で拒否を期待します。\n\n[Current backlog / close gates / priorities](runtime-limitations.md) / [Combined Evidence & Coverage](combined-evidence-coverage.md)\n`)
  console.log(summary)
  console.log('Representative combinations:', usability)
  console.log('Runtime support audit passed: population, catalog, live Power/weapon/copy/combination boundaries and assumptions.')
} finally {
  await server.close()
}
