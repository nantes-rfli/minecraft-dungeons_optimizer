import fs from 'node:fs'
import { createServer } from 'vite'

const write = process.argv.includes('--write')
const server = await createServer({ configFile: false, server: { middlewareMode: true, hmr: false, watch: null, ws: false } })
try {
  const module = await server.ssrLoadModule('/src/research/rangedAudit.ts')
  const weapons = module.buildRangedWeaponAudit()
  const enchants = module.buildRangedEnchantmentAudit()
  const errors = module.collectRangedAuditErrors(weapons, enchants)
  const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n'
  const report = (audit: typeof weapons, title: string) => [
    `# ${title}`, '', 'Generated by `npm run generate:ranged`. Category source: `src/research/rangedAudit.ts` + factual source snapshot. Combined Coverage is a read model only.', '',
    `Population: primary ${audit.population.primaryIds.length} / secondary ${audit.population.secondaryIds.length} / union ${audit.entries.length}.`,
    `Primary-only: ${audit.population.primaryOnly.join(', ') || 'none'}. Secondary-only: ${audit.population.secondaryOnly.join(', ') || 'none'}.`, '',
    'Target 1.17.0.0, publisher-claimed applicability; no independently verified gameplay samples. Raw game ID completeness is not claimed.', '',
    '| ID | Name | Runtime | Blockers |', '| --- | --- | --- | --- |',
    ...audit.entries.map((entry: { id: string; name: { en: string }; supportLevel: string; blockers: string[] }) => `| ${entry.id} | ${entry.name.en} | ${entry.supportLevel} | ${entry.blockers.join('; ').replaceAll('|', '\\|')} |`), '',
    'Full provenance, tier conflicts, family relationships, missing measurements and intrinsic boundaries are retained in the JSON audit.', '',
    '[Runtime and remaining gates](ranged-runtime.md) · [Combined Evidence & Coverage](combined-evidence-coverage.md)', '',
  ].join('\n')
  const generated = {
    'research/ranged-weapon-audit.json': json(weapons),
    'research/ranged-enchantment-audit.json': json(enchants),
    'docs/ranged-weapon-audit.md': report(weapons, 'Ranged weapon population / projectile audit'),
    'docs/ranged-enchantment-audit.md': report(enchants, 'Ranged enchantment audit'),
  }
  if (json(weapons) !== json(module.buildRangedWeaponAudit())) errors.push('Non-deterministic ranged audit')
  if (!write) for (const [file, content] of Object.entries(generated)) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) errors.push(`${file}: drift; run npm run generate:ranged`)
  }
  if (errors.length) throw new Error(errors.join('\n'))
  if (write) for (const [file, content] of Object.entries(generated)) fs.writeFileSync(file, content)
  console.log(`Ranged audit passed: weapons ${weapons.entries.length}, Limited ${weapons.selection.promotedIds.length}; enchantments ${enchants.entries.length}, Limited ${enchants.entries.filter((e: { supportLevel: string }) => e.supportLevel === 'limited').length}.`)
} finally { await server.close() }
