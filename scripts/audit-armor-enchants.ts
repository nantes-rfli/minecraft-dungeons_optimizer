import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'

const root = fileURLToPath(new URL('..', import.meta.url))
const server = await createServer({ root, configFile: false, server: { middlewareMode: true, hmr: false, watch: null, ws: false } })
try {
  const armor = await server.ssrLoadModule('/src/research/armorAudit.ts')
  const module = await server.ssrLoadModule('/src/research/armorEnchantmentAudit.ts')
  const errors = module.collectArmorEnchantmentAuditErrors(module.ARMOR_ENCHANTMENT_AUDIT, armor.ARMOR_AUDIT)
  if (errors.length) throw new Error(errors.join('\n'))
  const audit = module.ARMOR_ENCHANTMENT_AUDIT
  const summary = module.summarizeArmorEnchantmentAudit()
  const rows = audit.entries.map((entry: { name: string; tiers: readonly string[]; powerful: boolean; stackable: boolean; maxCopies: number; soulRestriction: string; mechanicFamily: string; runtimeReadiness: string; blockers: readonly string[]; builtIntoArmorIds: readonly string[] }) => `| ${entry.name} | ${entry.tiers.join(' / ')} | ${entry.powerful ? 'powerful' : 'common'} | ${entry.stackable ? `yes (${entry.maxCopies})` : 'no (1)'} | ${entry.soulRestriction} | ${entry.mechanicFamily} | ${entry.runtimeReadiness} | ${entry.builtIntoArmorIds.join(', ') || '—'} | ${entry.blockers.join('; ')} |`).join('\n')
  const readiness = Object.entries(summary.readiness).map(([status, count]) => `| ${status} | ${count} |`).join('\n')
  fs.writeFileSync(path.join(root, 'docs/armor-enchantment-audit.md'), [
    '# Armor enchantment audit — Phase 2-3C', '', 'Generated by `npm run audit:armor-enchants` from checked-in research data.', '',
    `Hero-accessible Armor enchantments: **${summary.population}**. Common **${summary.common}**, powerful **${summary.powerful}**, soul-only **${summary.soulOnly}**, utility-only **${summary.utilityOnly}**. Normal slots, built-ins, and gilded Tier I/II/III remain separate sources.`, '',
    '## Runtime readiness', '', '| Readiness | Count |', '| --- | ---: |', readiness, '',
    '## Entries', '', '| Enchantment | Tiers | Rarity | Stackable / game max | Soul restriction | Family | Readiness | Built into | Boundary |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |', rows, '',
    '## Runtime catalog', '',
    '- **Cool Down**: 18/29/37% from the version-targeted game-file audit, runtime one copy. The current Wiki 38% display conflict is retained; Battle Robe, external CDR, and multiple-copy compositions are rejected.',
    '- **Potion Barrier**: 90% for 5/7/9 seconds, with coverage derived from PotionState. Other runtime DR sources are rejected.',
    '- **Chilling**: 20/40/60%, one second every two seconds, explicit target shares, Control-only.', '',
    '- **Health Synergy**: 3/4/5% of resolved maximum Health per realized Artifact activation; nominal capacity includes overheal.',
    '- **Snowball**: every 5/3/1 seconds, two-second stun, one-target conservative Control-only model; boss eligibility is zero by default.',
    '- **Cowardice**: 20/30/40% with an explicit full-Health share; direct melee only.',
    '- **Protection**: 6/11/15% only as the sole DR source; depreciating combinations are rejected.', '',
  ].join('\n'))
  console.log(`Armor enchantments ${summary.population} · common ${summary.common} · powerful ${summary.powerful} · soul-only ${summary.soulOnly} · utility-only ${summary.utilityOnly}`)
} finally {
  await server.close()
}
