import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import type { Inventory } from '../src/core/types'
import { DEFAULT_SCENARIO } from '../src/data/scenarios'
import { readinessMelee, readinessRanged } from '../tests/inventoryReadinessFixtures'

const storageKey = 'minecraft-dungeons-optimizer.inventory.v1'
const SCENARIO_PRESETS_STORAGE_KEY = 'minecraft-dungeons-optimizer.scenario-presets.v1'
const serializeInventory = (inventory: Inventory) => JSON.stringify({ version: 6, inventory })
const presets = JSON.stringify({ version: 1, presets: [{ id: 'keep-preset', name: '保存条件を保持', scenario: DEFAULT_SCENARIO }] })

test('Inventory reasons lead to the exact same-name item, then evaluation, comparison and preserved storage', async ({ page }) => {
  const inventory: Inventory = { ...readinessMelee, rangedWeapons: [readinessRanged('bow', 'other-bow'), { ...readinessRanged('bow', 'target-bow'), observation: undefined }, { ...readinessRanged('harp-crossbow'), observation: undefined }], catalogItems: [{ instanceId: 'unsupported-artifact', category: 'artifact', catalogId: 'gong-of-weakening', powerLevel: 251 }] }
  await page.addInitScript(({ json, presets, presetKey, storageKey }) => {
    if (!localStorage.getItem(storageKey)) localStorage.setItem(storageKey, json)
    if (!localStorage.getItem(presetKey)) localStorage.setItem(presetKey, presets)
  }, { json: serializeInventory(inventory), presets, presetKey: SCENARIO_PRESETS_STORAGE_KEY, storageKey })
  await page.goto('/#/optimize')
  await page.getByText('詳細条件', { exact: true }).click()
  await page.getByRole('spinbutton', { name: '遠距離時間割合', exact: true }).fill('0.4')
  await page.evaluate(() => { window.location.hash = '/inventory' })
  const panel = page.getByRole('region', { name: '所持装備の評価可能性' })
  await expect(panel.getByRole('status')).toContainText('確認しました')
  await expect(panel.locator('.readiness-counts')).toContainText('評価可能2件')
  await expect(panel.locator('.readiness-counts')).toContainText('入力不足1件')
  await expect(panel.locator('.readiness-counts')).toContainText('未対応2件')
  await panel.getByText(/個体ごとの理由と必要な入力/).click()
  const target = panel.locator('.readiness-items > li').filter({ has: page.getByRole('button', { name: 'target-bowの入力を編集', exact: true }) })
  await expect(target).toContainText('完全発射周期')
  await expect(target).toContainText('矢数')
  const unsupported = panel.locator('.readiness-items > li').filter({ hasText: 'harp-crossbow' })
  await expect(unsupported).toContainText('Research-only')
  await expect(unsupported.getByRole('button')).toHaveCount(0)
  // Even a hidden target and a duplicate display name must not redirect the editor.
  await page.getByRole('spinbutton', { name: 'Power 最小値', exact: true }).fill('999')
  await page.getByRole('button', { name: 'お気に入りのみ', exact: true }).click()
  await panel.getByRole('button', { name: 'target-bowの入力を編集', exact: true }).click()
  const editor = page.locator('.inventory-collection details[data-instance-id="target-bow"]')
  await expect(editor).toHaveAttribute('open', '')
  await expect(editor.locator('.advanced-collection-fields')).toHaveAttribute('open', '')
  await expect(page.locator('.inventory-collection details[data-instance-id="other-bow"]')).not.toHaveAttribute('open', '')
  await expect(page.getByRole('spinbutton', { name: 'Power 最小値', exact: true })).toHaveValue('')
  await expect(page.getByRole('button', { name: 'お気に入りのみ', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await editor.getByRole('spinbutton', { name: 'target-bow damage', exact: true }).fill('0')
  await editor.getByRole('spinbutton', { name: 'target-bow cycle', exact: true }).fill('2')
  await editor.getByRole('spinbutton', { name: 'target-bow ammo', exact: true }).fill('20')
  await editor.getByRole('textbox', { name: 'target-bow 観測メモ', exact: true }).fill('SYNTHETIC UI TEST ONLY')
  await editor.getByRole('button', { name: '観測値を適用', exact: true }).click()
  await expect(editor.getByRole('alert')).toContainText('projectileDamage')
  await expect(panel.locator('.readiness-counts')).toContainText('入力不足1件')
  await editor.getByRole('spinbutton', { name: 'target-bow damage', exact: true }).fill('150')
  await editor.getByRole('button', { name: '観測値を適用', exact: true }).click()
  await expect(panel.locator('.readiness-counts')).toContainText('評価可能3件')
  await expect(panel.locator('.readiness-counts')).toContainText('入力不足0件')
  const actual = await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!).inventory, storageKey)
  expect(actual.weapons).toEqual(inventory.weapons)
  expect(actual.rangedWeapons.find((item: { instanceId: string }) => item.instanceId === 'other-bow')).toEqual(inventory.rangedWeapons![0])
  expect(actual.rangedWeapons.find((item: { instanceId: string }) => item.instanceId === 'target-bow').observation).toMatchObject({ projectileDamage: 150, shotCycleSeconds: 2, availableAmmo: 20 })
  expect(await page.evaluate((key) => localStorage.getItem(key), SCENARIO_PRESETS_STORAGE_KEY)).toBe(presets)
  await page.screenshot({ path: '/tmp/inventory-readiness-desktop.png', fullPage: true })
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(axe.violations).toEqual([])
  await panel.getByRole('link', { name: '最適化・装備比較へ進む' }).click()
  await page.getByRole('button', { name: '最適化する', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '探索完了' })).toBeVisible()
  await page.getByRole('button', { name: '用途別に評価する', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '用途別評価が完了' })).toBeVisible()
  await expect(page.locator('.assessment-table tbody tr').filter({ hasText: 'target-bow' })).toContainText('構成を見る')
  await page.reload()
  expect(await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!).inventory, storageKey)).toEqual(actual)
})

test('mobile Armor input completion refreshes readiness and keeps the layout within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  const inventory: Inventory = { ...readinessMelee, armors: [{ instanceId: 'target-armor', armorId: 'scale-mail', powerLevel: 251, enchantmentSlots: [{ candidates: ['cool-down'] }] }] }
  await page.addInitScript(({ key, json }) => localStorage.setItem(key, json), { key: storageKey, json: serializeInventory(inventory) })
  await page.goto('/#/inventory')
  const panel = page.getByRole('region', { name: '所持装備の評価可能性' })
  await expect(panel.locator('.readiness-counts')).toContainText('入力不足1件')
  await panel.getByText(/個体ごとの理由と必要な入力/).click()
  await panel.getByRole('button', { name: 'target-armorの入力を編集', exact: true }).click()
  const editor = page.locator('.inventory-collection details[data-instance-id="target-armor"]')
  await expect(editor).toHaveAttribute('open', '')
  await editor.getByRole('spinbutton', { name: 'target-armorの追加HP', exact: true }).fill('200')
  await expect(panel.locator('.readiness-counts')).toContainText('評価可能2件')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/inventory-readiness-mobile.png', fullPage: true })
})

test('a saved incompatible shot mode can be explicitly repaired and Catalog grid editing still opens its instance', async ({ page }) => {
  const ranged = readinessRanged('shortbow')
  const inventory: Inventory = { ...readinessMelee, rangedWeapons: [{ ...ranged, observation: { ...ranged.observation!, mode: 'uncharged' } }], catalogItems: [{ instanceId: 'catalog-sword', category: 'melee', catalogId: 'diamond-sword', powerLevel: 251 }] }
  await page.addInitScript(({ key, json }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, json) }, { key: storageKey, json: serializeInventory(inventory) })
  await page.goto('/#/optimize')
  await page.getByText('詳細条件', { exact: true }).click()
  await page.getByRole('spinbutton', { name: '遠距離時間割合', exact: true }).fill('0.4')
  await page.evaluate(() => { window.location.hash = '/inventory' })
  const panel = page.getByRole('region', { name: '所持装備の評価可能性' })
  await expect(panel.locator('.readiness-counts')).toContainText('入力不足1件')
  await panel.getByText(/個体ごとの理由と必要な入力/).click()
  await panel.getByRole('button', { name: 'shortbowの入力を編集', exact: true }).click()
  const editor = page.locator('.inventory-collection details[data-instance-id="shortbow"]')
  const mode = editor.getByRole('combobox', { name: 'shortbow 発射モード' })
  await expect(mode).toHaveValue('uncharged')
  await mode.selectOption('charged')
  await editor.getByRole('button', { name: '観測値を適用', exact: true }).click()
  await expect(panel.locator('.readiness-counts')).toContainText('評価可能2件')
  await page.getByRole('button', { name: '絞り込みを解除', exact: true }).click()
  await page.getByRole('button', { name: 'グリッド', exact: true }).click()
  await page.getByRole('option', { name: /Diamond Sword/ }).click()
  const selected = page.getByRole('complementary', { name: '選択した装備の詳細' })
  await selected.getByRole('button', { name: '編集', exact: true }).click()
  await selected.getByRole('button', { name: 'Enchant・金色を詳細編集', exact: true }).click()
  await expect(page.locator('.inventory-collection details[data-instance-id="catalog-sword"]')).toHaveAttribute('open', '')
})
