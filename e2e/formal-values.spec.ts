import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('configured field filtering preserves attack entries and trace and restores the full table', async ({ page }) => {
  await page.goto('/#/data/melee')
  const equipment = page.locator('[data-equipment-id="rapier"]')
  await equipment.locator(':scope > summary').click()
  const panel = equipment.locator('[data-formal-values-domain="rapier"]')
  await panel.locator(':scope > summary').click()
  const allRows = panel.locator('tbody tr')
  await expect(allRows).toHaveCount(127)
  const originalRefs = await allRows.evaluateAll((rows) => rows.map((row) => row.getAttribute('data-formal-projection')))
  const damageRows = allRows.filter({ has: page.getByRole('rowheader', { name: /^設定ダメージ ·/ }) })
  const damageRefs = await damageRows.evaluateAll((rows) => rows.map((row) => row.getAttribute('data-formal-projection')))
  const filter = panel.getByLabel('項目で絞り込む')
  await filter.selectOption({ label: '設定ダメージ' })
  await expect(allRows).toHaveCount(damageRefs.length)
  expect(await allRows.evaluateAll((rows) => rows.map((row) => row.getAttribute('data-formal-projection')))).toEqual(damageRefs)
  await expect(panel.getByRole('status')).toHaveText(`表示 ${damageRefs.length} / 127 行（取得不能 0 / 全体 0 行）`)
  await allRows.first().getByText('出典を確認', { exact: true }).click()
  await expect(allRows.first().getByText('Raw node', { exact: true })).toBeVisible()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await filter.selectOption('')
  await expect(allRows).toHaveCount(127)
  expect(await allRows.evaluateAll((rows) => rows.map((row) => row.getAttribute('data-formal-projection')))).toEqual(originalRefs)
})

