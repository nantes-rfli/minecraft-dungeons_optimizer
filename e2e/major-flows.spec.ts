async function navigate(page: Page, route: string) {
  const changed = await page.evaluate((next) => {
    if (window.location.hash === `#${next}`) return false
    window.location.hash = next
    return true
  }, route)
  if (changed) await expect(page.locator('#main-content')).toBeFocused()
}

async function useListView(page: Page) {
  const list = page.getByRole('button', { name: 'リスト', exact: true })
  if (await list.getAttribute('aria-pressed') !== 'true') await list.click()
}

async function addEquipment(page: Page, category: '近接' | '遠距離' | '防具' | 'アーティファクト', search: string, optionName: RegExp) {
  await page.getByRole('button', { name: '＋ 装備を登録' }).click()
  const drawer = page.getByRole('dialog', { name: '装備を登録' })
  await drawer.getByRole('button', { name: category, exact: true }).click()
  await drawer.getByPlaceholder('日本語名・英語名で検索').fill(search)
  await drawer.getByRole('option', { name: optionName }).click()
  await drawer.getByRole('button', { name: '装備に追加', exact: true }).click()
  await drawer.getByRole('button', { name: '装備登録を閉じる' }).click()
}

async function openRangedEditor(page: Page, name: string) {
  const item = page.locator('details.inventory-item').filter({ hasText: name })
  await item.locator(':scope > summary').click()
  await item.getByText('最適化に使う詳しい数値を入力する', { exact: true }).click()
  return item
}

async function openJson(page: Page) {
  await navigate(page, '/storage')
  return page.getByRole('textbox', { name: 'Inventory JSON' })
}
async function optimize(page: Page) {
  await navigate(page, '/optimize')
  await page.getByRole('button', { name: '最適化する', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '探索完了' })).toBeVisible({ timeout: 60_000 })
  await expect(page.locator('.result-meta')).toContainText('全探索')
}
async function audit(page: Page) {
  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  console.log(JSON.stringify(results.violations.map((item) => ({ id: item.id, nodes: item.nodes.map((node) => ({ target: node.target, summary: node.failureSummary })) }))))
  expect(results.violations).toEqual([])
}

